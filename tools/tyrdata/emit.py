"""Deterministic C emitters for generated ROM tables (agents.md §2)."""
import os

HEADER = "/* GENERATED by tools/gen.py from tyrian-data -- do not edit. */\n"


def c_array(ctype, name, values, per_line=12, fmt="0x{:04X}", attributes=""):
    rows = [", ".join(fmt.format(v) for v in values[i:i + per_line])
            for i in range(0, len(values), per_line)]
    return f"const {ctype} {name}[{len(values)}]{attributes} = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def write_if_changed(path, text):
    """Write only on change, so make/SGDK do not rebuild untouched outputs."""
    os.makedirs(os.path.dirname(path), exist_ok=True)
    if os.path.exists(path) and open(path).read() == text:
        return False
    with open(path, "w") as f:
        f.write(text)
    return True


def tile_array(name, values):
    """DMA-only graphics: physical ROM addresses, never dereferenced by CPU."""
    return c_array("u32", name, values, 6, "0x{:08X}",
                   ' __attribute__((section(".far_assets"), aligned(32)))')
